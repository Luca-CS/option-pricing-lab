"""Write docs/pricer-data.js from results/spx_calibration.json: the SPX results the demo page shows
(model-risk table, mixing-fraction sweep, fit errors). No market quote is included."""

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent

if __name__ == "__main__":
    cal = json.loads((ROOT / "results" / "spx_calibration.json").read_text())
    models = list(next(iter(cal["exotics"].values())).keys())
    data = {
        "snapshot": cal["meta"]["snapshot"][:10],
        "models": [m.replace(" (ATM vol)", "").replace(" (Dupire)", "") for m in models],
        "rows": [{"product": p, "prices": [round(row[m]["price"], 4) for m in models],
                  "stderr": [round(row[m]["stderr"], 4) for m in models]}
                 for p, row in cal["exotics"].items()],
        "mix_sweep": [{k: round(v, 4) for k, v in s.items()} for s in cal.get("mix_sweep", [])],
        "errors": [{"expiry": e["expiry"], "T": round(e["T"], 3), "quotes": e["n_quotes"],
                    "half_spread": round(e["median_spread_bp"] / 2, 1), "svi": round(e["svi_rmse_bp"], 1),
                    "heston": round(e["heston_rmse_bp"], 1), "lv": round(e["lv_mae_bp"], 1),
                    "slv": round(e["slv_mae_bp"], 1)} for e in cal["errors"]],
        "heston": {k: round(v, 4) for k, v in cal["heston"].items()},
    }
    out = ROOT / "docs" / "pricer-data.js"
    out.write_text("/* Generated by scripts/build_widget_data.py */\nwindow.PRICER_DATA = "
                   + json.dumps(data, indent=1) + ";\n")
    print("wrote", out)
