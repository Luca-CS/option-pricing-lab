"""Calibrate the implied surface (SSVI, then raw SVI) -> Heston -> SLV leverage, on the latest SPX
snapshot or on a simulated market, and write results/<source>_calibration.json and reports/figures/<source>_*.png.

    python scripts/run_calibration.py --source simulated
    python scripts/run_calibration.py --source spx        # needs scripts/download_spx.py first

Only derived quantities are written (parameters, curves rescaled to a spot of 100, model
repricing errors, charts): the raw Yahoo quotes never leave data/raw/.
"""

from __future__ import annotations

import argparse
import json
import sys
import time
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from optlab import HestonParams, Leverage, Market, SVISurface, heston_iv  # noqa: E402
from optlab.pipeline import calibrate_all, exotics_table, fit_errors, mix_sweep  # noqa: E402
from plots import plot_errors, plot_mix_sweep, plot_smiles, plot_surfaces  # noqa: E402

RESULTS = ROOT / "results"
FIGURES = ROOT / "reports" / "figures"

# simulated market: a known Heston model plus noise in the quotes
TRUE_HESTON = HestonParams(v0=0.025, kappa=1.8, theta=0.04, xi=0.75, rho=-0.75)
SIM_MATURITIES = (1 / 24, 1 / 12, 1 / 6, 0.25, 0.5, 0.75, 1.0, 1.5, 2.0)


def simulated_market(noise_bp=15, seed=1):
    """Quotes generated by TRUE_HESTON on a flat market (r 4 %, q 1.2 %), with Gaussian noise
    of noise_bp in implied vol and a bid-ask width of 4 noise_bp."""
    rng = np.random.default_rng(seed)
    market = Market.flat(100.0, 0.04, 0.012)
    slices = []
    for T in SIM_MATURITIES:
        F, D = float(market.F(T)), float(market.D(T))
        atm = np.sqrt(TRUE_HESTON.theta + (TRUE_HESTON.v0 - TRUE_HESTON.theta) * (1 - np.exp(-TRUE_HESTON.kappa * T))
                      / (TRUE_HESTON.kappa * T))
        k = np.linspace(-3.0, 2.0, 31) * atm * np.sqrt(T)
        K = F * np.exp(k)
        iv = heston_iv(F, K, T, TRUE_HESTON, D) + rng.normal(0, noise_bp * 1e-4, k.size)
        ok = np.isfinite(iv)  # prices below rounding in the far wings have no implied vol
        k, K, iv = k[ok], K[ok], iv[ok]
        slices.append({"T": T, "F": F, "D": D, "K": K, "k": k, "iv": iv,
                       "spread_iv": np.full(k.size, 4 * noise_bp * 1e-4), "expiry": f"{T:.3f}y"})
    return market, slices, {"source": "simulated", "true_heston": TRUE_HESTON.to_dict(), "noise_bp": noise_bp}


def spx_market():
    from optlab.data import build_iv_table, latest_snapshot, select_maturities

    market, slices, _, meta = build_iv_table(latest_snapshot())
    slices = select_maturities(slices)
    scale = 100.0 / market.spot
    market = market.scaled(100.0)
    for s in slices:
        s["F"] *= scale
        s["K"] = s["K"] * scale
    meta = {"source": "spx", "snapshot": meta["snapshot"], "zero_rate_curve": meta["zero_rate_curve"],
            "note": "SPX option quotes from Yahoo Finance (personal use). Spot rescaled to 100; "
                    "raw quotes are not published."}
    return market, slices, meta


def _round(x, nd=6):
    return np.round(np.asarray(x, dtype=float), nd).tolist()


def _plot_all(source, slices, surface, heston, errors, leverage, sweep, exotics):
    plot_smiles(slices, surface, heston, errors, FIGURES / f"{source}_smiles.png")
    plot_errors(errors, FIGURES / f"{source}_errors.png")
    plot_surfaces(surface, leverage, FIGURES / f"{source}_surfaces.png")
    if sweep:
        plot_mix_sweep(sweep, exotics, FIGURES / f"{source}_mix.png")


def replot(source):
    res = json.loads((RESULTS / f"{source}_calibration.json").read_text())
    _, slices, _ = spx_market() if source == "spx" else simulated_market()
    _plot_all(source, slices, SVISurface.from_dict(res["surface"]), HestonParams(**res["heston"]), res["errors"],
              Leverage.from_dict(res["slv"]["leverage"]), res.get("mix_sweep"), res["exotics"])
    print("charts redrawn for", source)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--source", choices=["spx", "simulated"], default="simulated")
    ap.add_argument("--mix", type=float, default=0.5)
    ap.add_argument("--particles", type=int, default=200_000)
    ap.add_argument("--paths", type=int, default=400_000)
    ap.add_argument("--skip-sweep", action="store_true")
    ap.add_argument("--replot", action="store_true", help="redraw the charts from the saved JSON only")
    args = ap.parse_args()
    if args.replot:
        replot(args.source)
        return

    t0 = time.time()
    market, slices, meta = spx_market() if args.source == "spx" else simulated_market()
    print(f"{args.source}: {len(slices)} maturities, {sum(len(s['k']) for s in slices)} quotes")
    fit = calibrate_all(market, slices, mix=args.mix, n_particles=args.particles)
    errors = fit_errors(fit, market, slices, n_paths=args.paths)
    exotics = exotics_table(fit, market)
    sweep = [] if args.skip_sweep else mix_sweep(fit, market, n_particles=args.particles)

    lev = fit["slv"].leverage
    keep = np.unique(np.concatenate([np.arange(0, len(lev.times), 3), [len(lev.times) - 1]]))
    result = {
        "meta": meta,
        "market": market.to_dict(),
        "surface": fit["surface"].to_dict(),
        "ssvi_start": fit["ssvi"].to_dict(),
        "arbitrage": fit["arbitrage"],
        "heston": fit["heston"].to_dict(),
        "feller": fit["heston"].feller(),
        "slv": {"mix": fit["slv"].mix, "particles": args.particles,
                "leverage": {"times": _round(lev.times[keep]), "x_grids": _round(lev.x_grids[keep], 5),
                             "values": _round(lev.values[keep], 5)}},
        "validation_paths": args.paths,
        "errors": errors,
        "exotics": exotics,
        "mix_sweep": sweep,
        "timings": fit["timings"] | {"total_s": time.time() - t0},
    }
    RESULTS.mkdir(exist_ok=True)
    FIGURES.mkdir(parents=True, exist_ok=True)
    path = RESULTS / f"{args.source}_calibration.json"
    path.write_text(json.dumps(result, indent=1))
    print("wrote", path)

    _plot_all(args.source, slices, fit["surface"], fit["heston"], errors, lev, sweep, exotics)
    print(f"done in {time.time() - t0:.0f} s")


if __name__ == "__main__":
    main()
