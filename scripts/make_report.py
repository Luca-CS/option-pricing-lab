"""Write reports/calibration.md from results/*_calibration.json (run after run_calibration.py)."""

from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
NAMES = {"v0": "v0", "kappa": "kappa", "theta": "theta", "xi": "xi (vol of vol)", "rho": "rho"}


def _errors_table(errors):
    has_spread = errors[0].get("median_spread_bp") is not None
    head = "| Expiry | T (y) | Quotes |" + (" Half bid-ask |" if has_spread else "") + \
           " SVI | SSVI (start) | Heston | Local vol | SLV | SLV max | MC s.e. |"
    lines = [head, "|" + "---|" * (head.count("|") - 1)]
    for e in errors:
        cells = [e["expiry"], f"{e['T']:.2f}", str(e["n_quotes"])]
        if has_spread:
            cells.append(f"{e['median_spread_bp'] / 2:.1f}")
        cells += [f"{e['svi_rmse_bp']:.1f}", f"{e['ssvi_rmse_bp']:.0f}", f"{e['heston_rmse_bp']:.0f}",
                  f"{e['lv_mae_bp']:.1f}", f"{e['slv_mae_bp']:.1f}", f"{e['slv_max_bp']:.1f}",
                  f"{e['mc_stderr_bp']:.1f}"]
        lines.append("| " + " | ".join(cells) + " |")
    return "\n".join(lines)


def _exotics_table(exotics):
    models = list(next(iter(exotics.values())).keys())
    lines = ["| Product (1 year, % of spot) | " + " | ".join(models) + " |", "|---" * (len(models) + 1) + "|"]
    for p, row in exotics.items():
        lines.append(f"| {p} | " + " | ".join(f"{row[m]['price']:.3f} ({row[m]['stderr']:.3f})" for m in models) + " |")
    return "\n".join(lines)


def _sweep_table(sweep):
    lines = ["| Mixing fraction | Down-and-out call, H 80 % | Up-and-out call, H 120 % | ATM vol error (bp) |",
             "|---|---|---|---|"]
    for s in sweep:
        lines.append(f"| {s['mix']:.2f} | {s['dao']:.3f} ({s['dao_se']:.3f}) | {s['uao']:.3f} ({s['uao_se']:.3f}) | "
                     f"{s['atm_iv_error_bp']:+.1f} |")
    return "\n".join(lines)


def _heston_table(fit, true=None):
    if true is None:
        lines = ["| Parameter | Calibrated |", "|---|---|"]
        lines += [f"| {NAMES[k]} | {fit[k]:.4f} |" for k in NAMES]
    else:
        lines = ["| Parameter | True | Calibrated |", "|---|---|---|"]
        lines += [f"| {NAMES[k]} | {true[k]:.4f} | {fit[k]:.4f} |" for k in NAMES]
    return "\n".join(lines)


def section(res, source):
    out = []
    arb = res["arbitrage"]
    t = res["timings"]
    if source == "spx":
        snap = res["meta"]["snapshot"]
        zc = res["meta"]["zero_rate_curve"]
        out.append(f"## SPX, snapshot of {snap[:10]} ({snap[11:16]} New York)\n")
        out.append(f"{len(res['errors'])} maturities from {res['errors'][0]['T']:.2f} to {res['errors'][-1]['T']:.2f} "
                   f"years, {sum(e['n_quotes'] for e in res['errors'])} out-of-the-money quotes after cleaning. "
                   f"Discounting: zero rate {100 * zc['intercept']:.2f} % + {100 * zc['slope']:.2f} % x T, implied "
                   f"from put-call parity on {zc['n_maturities']} maturities beyond two months.\n")
    else:
        out.append("## Simulated market\n")
        out.append(f"Quotes generated by a known Heston model on 9 maturities from two weeks to two years, with "
                   f"{res['meta']['noise_bp']} bp of Gaussian noise on the implied vols. The calibration must find "
                   f"the parameters back.\n")
    out.append("### Step 1: implied surface\n")
    out.append(f"Static-arbitrage checks on the fitted surface: minimum of Gatheral's g(k) = {arb['min_g']:.3f} "
               f"(butterfly-free: {arb['butterfly_free']}), minimum calendar increment of total variance = "
               f"{arb['min_calendar_increment']:.1e} (calendar-free on k in [-1, 0.5]: {arb['calendar_free']}). "
               f"Fit time {t['surface_s']:.0f} s.\n")
    out.append("### Step 2: Heston\n")
    out.append(_heston_table(res["heston"], res["meta"].get("true_heston")) +
               f"\n\nFeller ratio 2 kappa theta / xi^2 = {res['feller']:.2f}"
               f"{' (below 1: the variance can touch zero)' if res['feller'] < 1 else ''}. "
               f"Fit time {t['heston_s']:.0f} s.\n")
    out.append("### Step 3: SLV leverage\n")
    out.append(f"Mixing fraction {res['slv']['mix']:.2f} (the SLV variance has {res['slv']['mix']:.0%} of the Heston "
               f"vol of vol), {res['slv']['particles']:,} particles, graded time grid. Calibration time "
               f"{t['leverage_s']:.0f} s.\n")
    out.append("### Errors per maturity (basis points of implied vol)\n")
    out.append("SVI, SSVI and Heston: RMSE against every quote. Local vol and SLV: mean absolute error of a Monte "
               f"Carlo repricing ({res.get('validation_paths', 300_000):,} paths, 9 strikes from -2 to +1.5 ATM "
               "standard deviations) against the SVI surface they are built on; the last column is the Monte Carlo "
               "standard error.\n")
    out.append(_errors_table(res["errors"]) + "\n")
    out.append(f"![Smiles](figures/{source}_smiles.png)\n")
    out.append(f"![Errors](figures/{source}_errors.png)\n")
    out.append(f"![Local volatility and leverage](figures/{source}_surfaces.png)\n")
    out.append("### Model risk: same vanillas, different exotics\n")
    out.append("Monte Carlo prices in % of spot, standard errors in brackets. Black-Scholes uses the 1-year ATM vol.\n")
    out.append(_exotics_table(res["exotics"]) + "\n")
    if res.get("mix_sweep"):
        out.append("Barrier prices when the leverage is recalibrated for each mixing fraction (0 = local vol, "
                   "1 = full Heston vol of vol): vanillas stay on the surface, barriers move.\n")
        out.append(_sweep_table(res["mix_sweep"]) + "\n")
        bad = [x for x in res["mix_sweep"] if abs(x["atm_iv_error_bp"]) > 20]
        if bad:
            out.append(f"At a mixing fraction of {bad[0]['mix']:.2f} the leverage no longer reproduces the ATM vol "
                       f"({bad[0]['atm_iv_error_bp']:+.0f} bp): with the full calibrated vol of vol "
                       f"(xi = {res['heston']['xi']:.2f}) the leverage needed where the variance is small hits its "
                       "bounds. That point is not a valid SLV calibration.\n")
        out.append(f"![Mixing fraction](figures/{source}_mix.png)\n")
    return "\n".join(out)


def main():
    parts = ["# Calibration report\n",
             "Generated by `scripts/run_calibration.py` and `scripts/make_report.py`. Three steps: an implied "
             "surface (extended SSVI as an arbitrage-free start, then raw SVI slices under no-arbitrage "
             "constraints), Heston on the same vanillas, then the leverage function of the Heston SLV model by "
             "the particle method. Errors are in basis points of implied volatility (1 bp = 0.01 vol point).\n"]
    for source in ("spx", "simulated"):
        path = ROOT / "results" / f"{source}_calibration.json"
        if path.exists():
            parts.append(section(json.loads(path.read_text()), source))
    out = ROOT / "reports" / "calibration.md"
    out.write_text("\n".join(parts), encoding="utf-8")
    print("wrote", out)


if __name__ == "__main__":
    main()
