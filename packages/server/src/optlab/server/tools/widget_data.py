"""Write docs/pricer-data.js from <results>/spx_calibration.json: the SPX results the demo page shows
(model-risk table, mixing-fraction sweep, fit errors). No market quote is included (`optlab demo widget-data`; the
page and this file stay until session 2 replaces docs/lab.js)."""

from __future__ import annotations

import json
from pathlib import Path

from optlab.server.settings import Settings, repository_root
from optlab.server.tools import say


def main(log=say) -> Path:
    repo = repository_root()
    if repo is None:
        raise RuntimeError("demo widget-data writes docs/ of the repository: run it from a checkout")

    cal = json.loads((Settings.load().results / "spx_calibration.json").read_text())
    models = list(next(iter(cal["exotics"].values())).keys())
    data = {
        "snapshot": cal["meta"]["snapshot"][:10],
        "models": [m.replace(" (ATM vol)", "").replace(" (Dupire)", "") for m in models],
        "rows": [
            {
                "product": p,
                "prices": [round(row[m]["price"], 4) for m in models],
                "stderr": [round(row[m]["stderr"], 4) for m in models],
            }
            for p, row in cal["exotics"].items()
        ],
        "mix_sweep": [{k: round(v, 4) for k, v in s.items()} for s in cal.get("mix_sweep", [])],
        "errors": [
            {
                "expiry": e["expiry"],
                "T": round(e["T"], 3),
                "quotes": e["n_quotes"],
                "half_spread": round(e["median_spread_bp"] / 2, 1),
                "svi": round(e["svi_rmse_bp"], 1),
                "heston": round(e["heston_rmse_bp"], 1),
                "lv": round(e["lv_mae_bp"], 1),
                "slv": round(e["slv_mae_bp"], 1),
            }
            for e in cal["errors"]
        ],
        "heston": {k: round(v, 4) for k, v in cal["heston"].items()},
    }
    out = repo / "docs" / "pricer-data.js"
    out.write_text(
        "/* Generated by optlab demo widget-data */\nwindow.PRICER_DATA = " + json.dumps(data, indent=1) + ";\n"
    )
    log("wrote", out)
    return out
